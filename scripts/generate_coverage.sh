def parse_opencover_xml(xml_path):
    """Parse an OpenCover XML file and return coverage stats."""
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
        summary = root.find('Summary')
        if summary is not None:
            return {
                'num_seq': int(summary.get('numSequencePoints', 0)),
                'visited_seq': int(summary.get('visitedSequencePoints', 0)),
                'pct': float(summary.get('sequenceCoverage', 0))
