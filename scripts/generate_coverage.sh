def parse_opencover_detailed(xml_path):
    """Parse OpenCover XML and extract per-file coverage data."""
    files_data = {}
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
        
        for module in root.findall('.//Module'):
            # Build file uid -> path mapping
            file_map = {}
            for f in module.findall('.//File'):
                file_map[f.get('uid')] = f.get('fullPath', 'Unknown')
            
            # Collect coverage per file
            for cls in module.findall('.//Class'):
                for method in cls.findall('.//Method'):
                    for seq_point in method.findall('.//SequencePoint'):
                        file_id = seq_point.get('fileid')
                        if file_id and file_id in file_map:
                            file_path = file_map[file_id]
                            if file_path not in files_data:
                                files_data[file_path] = {'total': 0, 'covered': 0}
                            files_data[file_path]['total'] += 1
                            if int(seq_point.get('vc', '0')) > 0:
                                files_data[file_path]['covered'] += 1
    except Exception as e:
        print(f"Warning: {e}")
    return files_data

